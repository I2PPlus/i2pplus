package com.southernstorm.noise.protocol;

import static org.junit.Assert.*;

import java.util.Arrays;

import javax.crypto.ShortBufferException;

import org.junit.Test;

/**
 * The cipher state refuses an argument range that does not lie inside its buffer,
 * and refuses it before setup() has rewritten the nonce schedule and the one-time
 * MAC key - a call that fails after that point has changed what the next packet on
 * the same state is encrypted with, which is the part an exception cannot undo.
 * <p>
 * The last case pins the other half of the upstream change we deliberately did not
 * take: a destroyed state stays reusable, because ECIESAEADEngine keeps one cipher
 * per thread, destroys it in a finally, and re-arms it with initializeKey() on the
 * next use.
 *
 * @since 0.9.72+
 */
public class ChaChaPolyRangeTest {

    /**
     * One instance per test method, as JUnit builds a fresh test object for each
     * one; the class carries only the pinned reference packet.
     *
     * @since 0.9.72+
     */
    public ChaChaPolyRangeTest() {}

    /**
     * Ciphertext plus tag for the 0x5a key at nonce 11, one zero byte of plaintext
     * and no associated data. Generated by the JDK's own ChaCha20-Poly1305, with
     * the nonce in the last eight bytes of the IV, little-endian, as Noise defines
     * it, and pinned here because the build forks its test JVM on Java 8, which has
     * no such cipher: SunJCE gained it in Java 11. The same packet as the one
     * {@link ChaChaPolyCloneIsolationTest} pins.
     */
    private static final String REF_ZERO_BYTE_AT_11 = "7c4ffda38f0986ffe4590929a0bd2df40e";

    /**
     * An associated-data range running past the end of its buffer is rejected, and
     * the state is left exactly as it was: the next packet on it is the packet that
     * would have been produced had the failed call never happened. At HEAD the
     * range reached poly.update() unchecked, so the call threw an index exception
     * and had already derived a fresh MAC key and advanced the nonce schedule.
     *
     * @throws Exception if the cipher state rejects the good call's output buffer
     */
    @Test
    public void testAdRangePastTheEndRejectedAndStateUnchanged() throws Exception {
        byte[] key = filled((byte) 0x5a, 32);
        byte[] one = new byte[1];
        ChaChaPolyCipherState cipher = state(key, 11);
        byte[] first = new byte[17];
        cipher.encryptWithAd(null, one, 0, first, 0, 1);
        assertArrayEquals(fromHex(REF_ZERO_BYTE_AT_11), first);
        byte[] ad = filled((byte) 0x11, 4);
        try {
            cipher.encryptWithAd(ad, 3, 2, one, 0, new byte[17], 0, 1);
            fail("An ad range running past the end of the buffer must be rejected");
        } catch (ShortBufferException e) {
            // expected, and the only exception type the callers already catch
        }
        byte[] after = new byte[17];
        cipher.encryptWithAd(null, one, 0, after, 0, 1);
        // The same two good calls on a state that never saw the rejected one.
        ChaChaPolyCipherState twin = state(key, 11);
        byte[] unused = new byte[17];
        twin.encryptWithAd(null, one, 0, unused, 0, 1);
        byte[] expected = new byte[17];
        twin.encryptWithAd(null, one, 0, expected, 0, 1);
        assertArrayEquals("the rejected call changed what the next packet encrypts to",
                          expected, after);
    }

    /**
     * A negative destination offset used to make the computed space larger than the
     * buffer rather than smaller, so the size checks passed and the copy ran off the
     * front of it.
     *
     * @throws Exception if the cipher state rejects the output buffer
     */
    @Test
    public void testNegativeCiphertextOffsetRejected() throws Exception {
        ChaChaPolyCipherState cipher = state(filled((byte) 0x5a, 32), 11);
        try {
            cipher.encryptWithAd(null, new byte[1], 0, new byte[17], -1, 1);
            fail("A negative output offset must be rejected");
        } catch (ShortBufferException e) {
            // expected
        }
    }

    /**
     * A plaintext range running past the end of its buffer is rejected before the
     * keystream is generated, not in the middle of xoring it.
     *
     * @throws Exception if the cipher state rejects the output buffer
     */
    @Test
    public void testPlaintextRangePastTheEndRejected() throws Exception {
        ChaChaPolyCipherState cipher = state(filled((byte) 0x5a, 32), 11);
        try {
            cipher.encryptWithAd(null, new byte[4], 0, new byte[24], 0, 8);
            fail("A plaintext range running past the end of the buffer must be rejected");
        } catch (ShortBufferException e) {
            // expected
        }
    }

    /**
     * A key range that cannot hold 32 bytes is rejected by initializeKey(), which
     * has no checked exception to report it with.
     */
    @Test
    public void testKeyRangePastTheEndRejected() {
        ChaChaPolyCipherState cipher = new ChaChaPolyCipherState();
        try {
            cipher.initializeKey(filled((byte) 0x5a, 32), 20);
            fail("A key range running past the end of the buffer must be rejected");
        } catch (IllegalArgumentException e) {
            // expected
        }
        assertFalse("a rejected key must not leave a half-set key behind", cipher.hasKey());
    }

    /**
     * The reuse ECIESAEADEngine depends on: one cipher per thread, destroyed in a
     * finally, re-armed with initializeKey() by the next caller on that thread. A
     * destroyed state that refused to be keyed again would fail every garlic AEAD
     * block after the first, which is why the upstream change's destroyed flag was
     * not taken with its range checks.
     *
     * @throws Exception if the cipher state rejects the output buffer
     */
    @Test
    public void testDestroyThenReinitializeStillEncrypts() throws Exception {
        byte[] key = filled((byte) 0x5a, 32);
        ChaChaPolyCipherState cipher = state(key, 11);
        byte[] first = new byte[17];
        cipher.encryptWithAd(null, new byte[1], 0, first, 0, 1);
        cipher.destroy();
        cipher.initializeKey(key, 0);
        cipher.setNonce(11);
        byte[] again = new byte[17];
        cipher.encryptWithAd(null, new byte[1], 0, again, 0, 1);
        assertArrayEquals(fromHex(REF_ZERO_BYTE_AT_11), again);
        assertArrayEquals(first, again);
    }

    /**
     * A cipher state with a key and a starting nonce.
     *
     * @param key the 32-byte key
     * @param nonce the first nonce to use
     * @return a cipher state keyed with key and set to start at nonce
     */
    private static ChaChaPolyCipherState state(byte[] key, long nonce) {
        ChaChaPolyCipherState cipher = new ChaChaPolyCipherState();
        cipher.initializeKey(key, 0);
        cipher.setNonce(nonce);
        return cipher;
    }

    /**
     * A pinned reference packet decoded for comparison.
     *
     * @param hex the ciphertext with its tag, as lower-case hex pairs
     * @return the bytes the hex stands for
     */
    private static byte[] fromHex(String hex) {
        byte[] data = new byte[hex.length() / 2];
        for (int i = 0; i < data.length; i++)
            data[i] = (byte) Integer.parseInt(hex.substring(2 * i, 2 * i + 2), 16);
        return data;
    }

    /**
     * @param value the byte to fill with
     * @param length how many bytes
     * @return the filled array
     */
    private static byte[] filled(byte value, int length) {
        byte[] data = new byte[length];
        Arrays.fill(data, value);
        return data;
    }
}
