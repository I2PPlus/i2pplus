def translate_po(en_path, sk_path, translations):
    po = polib.pofile(en_path)
    matched = 0
    for entry in po:
        if entry.msgid in translations:
            if entry.msgid_plural:
                t0 = translations[entry.msgid]
                t1 = translations.get(entry.msgid_plural, t0)
                entry.msgstr_plural[0] = t0
                entry.msgstr_plural[1] = t1
            else:
                entry.msgstr = translations[entry.msgid]
            matched += 1
    po.metadata['Language'] = 'sk'
    po.save(sk_path)
    total = sum(1 for e in po if e.msgstr or e.msgstr_plural or (isinstance(e.msgstr, list) and any(e.msgstr)))
    print(f"  {sk_path}: {total}/{len(po)} translated ({matched} matched from dict)")

